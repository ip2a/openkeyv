//! The public shared-memory store: trait implementations over [`ShmClient`].
//!
//! Reads are lock-free. Every mutation serializes through one writer slot:
//! the process-local tokio mutex plus the cross-process flock. The flock is
//! acquired without blocking on the happy path and via `spawn_blocking` when
//! another process holds it, so the async runtime never parks on a file lock.

use super::change::ShmChangeStream;
use super::client::{Require, RemoveOutcome, ShmClient, UpsertOutcome};
use super::config::{
    ShmCreateConfig, DEFAULT_COLLECTION, MAX_COLLECTION_BYTES, MAX_KEY_BYTES,
};
use super::entry::EntrySnapshot;
use super::layout::{RECORD_ENTRY, RECORD_REGISTRY};
use crate::change::ChangeFeedRequest;
use crate::error::{Error, Result};
use crate::protocol::{
    AsyncChangeFeed, AsyncCompareAndSwap, AsyncCull, AsyncDestroyCollection, AsyncDestroyStore,
    AsyncEnumerateCollections, AsyncEnumerateKeys, AsyncKeyValue, CompareAndDeleteResult,
    CompareAndSwapResult, Revision, RevisionedValue,
};
use crate::value::{Value, ValueKind};
use async_trait::async_trait;
use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::time::SystemTime;

/// Mirrors the memory store's page defaults: both limits cap at 10 000.
const DEFAULT_PAGE_SIZE: usize = 10_000;
const PAGE_LIMIT: usize = 10_000;

/// Multi-process shared-memory key-value store.
///
/// One backing file per store; any number of processes on the same machine
/// attach to it and share data, capacity, and the change feed. Creation is an
/// explicit, exclusive operation ([`ShmStore::create`]); every other process
/// uses [`ShmStore::open`].
pub struct ShmStore {
    client: Arc<ShmClient>,
}

impl ShmStore {
    /// Initialize (or reset) the backing file at `config.path`. Exclusive:
    /// fails with [`Error::StoreInUse`] while any other process holds the
    /// store attached.
    pub fn create(config: ShmCreateConfig) -> Result<Self> {
        Ok(Self {
            client: Arc::new(ShmClient::create(&config)?),
        })
    }

    /// Attach to an existing store, replaying crash recovery first.
    pub fn open(path: impl Into<PathBuf>) -> Result<Self> {
        Ok(Self {
            client: Arc::new(ShmClient::open(path.into().as_path())?),
        })
    }

    pub fn path(&self) -> &Path {
        self.client.path()
    }

    /// Identifier persisted in the file header; stable across attach/detach,
    /// regenerated by `create` and `destroy`.
    pub fn store_id(&self) -> [u8; 16] {
        self.client.store_id()
    }

    /// Whether the store carries a change feed. Subscribing to a store
    /// created with `change_retention = 0` is an error, matching the
    /// capability advertised by the store handle.
    pub fn change_feed_enabled(&self) -> bool {
        self.client.layout.change_retention > 0
    }

    fn collection_name(collection: Option<&str>) -> &str {
        collection.unwrap_or(DEFAULT_COLLECTION)
    }

    /// Run one mutation under the writer lock. Fast path takes the flock
    /// without blocking; contended path parks the mutation in
    /// `spawn_blocking` so no async task ever blocks a runtime worker.
    async fn mutate<R: Send + 'static>(
        &self,
        op: impl FnOnce(&ShmClient) -> Result<R> + Send + 'static,
    ) -> Result<R> {
        let _guard = self.client.local_write.lock().await;
        let client = Arc::clone(&self.client);
        if client.try_write_lock()? {
            let result = op(&client);
            client.unlock_write();
            result
        } else {
            tokio::task::spawn_blocking(move || {
                client.block_write_lock()?;
                let result = op(&client);
                client.unlock_write();
                result
            })
            .await
            .map_err(|error| Error::StoreConnection {
                message: format!("shm writer task failed: {error}"),
            })?
        }
    }

    fn decode_value(snapshot: &EntrySnapshot) -> Result<Value> {
        let kind = ValueKind::from_tag(snapshot.value_kind as u8).ok_or_else(|| {
            Error::StoreFormat {
                message: format!(
                    "entry holds unknown value kind tag {}",
                    snapshot.value_kind
                ),
            }
        })?;
        Ok(Value::new_unchecked(kind, snapshot.value.clone()))
    }

    fn revisioned_value(snapshot: &EntrySnapshot) -> Result<RevisionedValue> {
        Ok(RevisionedValue {
            value: Self::decode_value(snapshot)?,
            revision: Revision::from_bytes(snapshot.revision),
            ttl: snapshot.ttl_remaining(now_unix_ms()),
        })
    }

    fn validate_ttl(ttl_secs: f64) -> Result<()> {
        if !ttl_secs.is_finite() || ttl_secs <= 0.0 {
            return Err(Error::InvalidTtl(format!(
                "must be finite and greater than zero, got {ttl_secs}"
            )));
        }
        let ttl_millis = ttl_secs * 1000.0;
        if !ttl_millis.is_finite() || ttl_millis > i64::MAX as f64 {
            return Err(Error::InvalidTtl(format!(
                "exceeds the supported range: {ttl_secs}"
            )));
        }
        Ok(())
    }

    fn validate_identifiers(collection: &str, key: &str) -> Result<()> {
        if collection.len() > MAX_COLLECTION_BYTES {
            return Err(Error::InvalidOperation(format!(
                "collection name exceeds {MAX_COLLECTION_BYTES} bytes"
            )));
        }
        if key.len() > MAX_KEY_BYTES {
            return Err(Error::InvalidOperation(format!(
                "key exceeds {MAX_KEY_BYTES} bytes"
            )));
        }
        Ok(())
    }
}

fn now_unix_ms() -> u64 {
    SystemTime::now()
        .duration_since(SystemTime::UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

#[async_trait]
impl AsyncKeyValue for ShmStore {
    async fn get(&self, key: &str, collection: Option<&str>) -> Result<Option<Value>> {
        let cname = Self::collection_name(collection);
        match self.client.find_snapshot(RECORD_ENTRY, cname, key)? {
            Some(snapshot) => Ok(Some(Self::decode_value(&snapshot)?)),
            None => Ok(None),
        }
    }

    async fn ttl(
        &self,
        key: &str,
        collection: Option<&str>,
    ) -> Result<Option<(Value, Option<f64>)>> {
        let cname = Self::collection_name(collection);
        match self.client.find_snapshot(RECORD_ENTRY, cname, key)? {
            Some(snapshot) => Ok(Some((
                Self::decode_value(&snapshot)?,
                snapshot.ttl_remaining(now_unix_ms()),
            ))),
            None => Ok(None),
        }
    }

    async fn put(
        &self,
        key: &str,
        value: Value,
        collection: Option<&str>,
        ttl: Option<f64>,
    ) -> Result<()> {
        Self::validate_identifiers(Self::collection_name(collection), key)?;
        if let Some(secs) = ttl {
            Self::validate_ttl(secs)?;
        }
        let cname = Self::collection_name(collection).to_string();
        let key = key.to_string();
        self.mutate(move |client| {
            client.perform_upsert(&cname, &key, &value, ttl, Require::Any)?;
            Ok(())
        })
        .await
    }

    async fn delete(&self, key: &str, collection: Option<&str>) -> Result<bool> {
        let cname = Self::collection_name(collection).to_string();
        let key = key.to_string();
        self.mutate(move |client| {
            Ok(matches!(
                client.perform_remove(RECORD_ENTRY, &cname, &key, None, false)?,
                RemoveOutcome::Removed
            ))
        })
        .await
    }

    async fn get_many(
        &self,
        keys: &[String],
        collection: Option<&str>,
    ) -> Result<Vec<Option<Value>>> {
        let mut values = Vec::with_capacity(keys.len());
        for key in keys {
            values.push(self.get(key, collection).await?);
        }
        Ok(values)
    }

    async fn ttl_many(
        &self,
        keys: &[String],
        collection: Option<&str>,
    ) -> Result<Vec<Option<(Value, Option<f64>)>>> {
        let mut values = Vec::with_capacity(keys.len());
        for key in keys {
            values.push(self.ttl(key, collection).await?);
        }
        Ok(values)
    }

    async fn put_many(
        &self,
        keys: &[String],
        values: &[Value],
        collection: Option<&str>,
        ttl: Option<f64>,
    ) -> Result<()> {
        if keys.len() != values.len() {
            return Err(Error::InvalidOperation(format!(
                "put_many received {} keys and {} values",
                keys.len(),
                values.len()
            )));
        }
        if let Some(secs) = ttl {
            Self::validate_ttl(secs)?;
        }
        for (key, value) in keys.iter().zip(values) {
            self.put(key, value.clone(), collection, ttl).await?;
        }
        Ok(())
    }

    async fn delete_many(&self, keys: &[String], collection: Option<&str>) -> Result<usize> {
        let mut deleted = 0;
        for key in keys {
            if self.delete(key, collection).await? {
                deleted += 1;
            }
        }
        Ok(deleted)
    }
}

#[async_trait]
impl AsyncCompareAndSwap for ShmStore {
    async fn get_with_revision(
        &self,
        key: &str,
        collection: Option<&str>,
    ) -> Result<Option<RevisionedValue>> {
        let cname = Self::collection_name(collection);
        match self.client.find_snapshot(RECORD_ENTRY, cname, key)? {
            Some(snapshot) => Ok(Some(Self::revisioned_value(&snapshot)?)),
            None => Ok(None),
        }
    }

    async fn compare_and_swap(
        &self,
        key: &str,
        expected: Option<&Revision>,
        value: Value,
        collection: Option<&str>,
        ttl: Option<f64>,
    ) -> Result<CompareAndSwapResult> {
        Self::validate_identifiers(Self::collection_name(collection), key)?;
        if let Some(secs) = ttl {
            Self::validate_ttl(secs)?;
        }
        let require = match expected {
            Some(revision) => Require::ExactRevision(*revision.as_bytes()),
            None => Require::Absent,
        };
        let cname = Self::collection_name(collection).to_string();
        let key = key.to_string();
        self.mutate(move |client| {
            Ok(match client.perform_upsert(&cname, &key, &value, ttl, require)? {
                UpsertOutcome::Applied { revision } => CompareAndSwapResult::Applied {
                    revision: Revision::from_bytes(revision),
                },
                UpsertOutcome::Conflict { current } => CompareAndSwapResult::Conflict {
                    current: match current {
                        Some(snapshot) => Some(ShmStore::revisioned_value(&snapshot)?),
                        None => None,
                    },
                },
            })
        })
        .await
    }

    async fn compare_and_delete(
        &self,
        key: &str,
        expected: &Revision,
        collection: Option<&str>,
    ) -> Result<CompareAndDeleteResult> {
        let cname = Self::collection_name(collection).to_string();
        let key = key.to_string();
        let expected = *expected;
        self.mutate(move |client| {
            Ok(
                match client.perform_remove(
                    RECORD_ENTRY,
                    &cname,
                    &key,
                    Some(&expected),
                    false,
                )? {
                    RemoveOutcome::Removed => CompareAndDeleteResult::Deleted,
                    RemoveOutcome::Absent => CompareAndDeleteResult::Conflict { current: None },
                    RemoveOutcome::Conflict { current } => CompareAndDeleteResult::Conflict {
                        current: match current {
                            Some(snapshot) => Some(ShmStore::revisioned_value(&snapshot)?),
                            None => None,
                        },
                    },
                },
            )
        })
        .await
    }
}

#[async_trait]
impl AsyncCull for ShmStore {
    async fn cull(&self) -> Result<()> {
        self.mutate(|client| {
            for hit in client.scan_hits(Some(RECORD_ENTRY), None, true)? {
                client.perform_remove(RECORD_ENTRY, &hit.collection, &hit.key, None, true)?;
            }
            Ok(())
        })
        .await
    }
}

#[async_trait]
impl AsyncEnumerateKeys for ShmStore {
    async fn keys(&self, collection: Option<&str>, limit: Option<usize>) -> Result<Vec<String>> {
        let cname = Self::collection_name(collection);
        let limit = limit.unwrap_or(DEFAULT_PAGE_SIZE).min(PAGE_LIMIT);
        let hits = self.client.scan_hits(Some(RECORD_ENTRY), Some(cname), false)?;
        Ok(hits
            .into_iter()
            .filter(|hit| !hit.expired)
            .take(limit)
            .map(|hit| hit.key)
            .collect())
    }
}

#[async_trait]
impl AsyncEnumerateCollections for ShmStore {
    async fn collections(&self, limit: Option<usize>) -> Result<Vec<String>> {
        let limit = limit.unwrap_or(DEFAULT_PAGE_SIZE).min(PAGE_LIMIT);
        let mut names: Vec<String> = self
            .client
            .scan_hits(Some(RECORD_REGISTRY), None, false)?
            .into_iter()
            .map(|hit| hit.collection)
            .collect();
        names.sort();
        names.dedup();
        Ok(names.into_iter().take(limit).collect())
    }
}

#[async_trait]
impl AsyncDestroyStore for ShmStore {
    async fn destroy(&self) -> Result<bool> {
        self.mutate(|client| client.destroy()).await
    }
}

#[async_trait]
impl AsyncDestroyCollection for ShmStore {
    async fn destroy_collection(&self, collection: &str) -> Result<bool> {
        let cname = collection.to_string();
        self.mutate(move |client| {
            let existed = !client
                .scan_hits(Some(RECORD_REGISTRY), Some(&cname), false)?
                .is_empty();
            for hit in client.scan_hits(Some(RECORD_ENTRY), Some(&cname), false)? {
                client.perform_remove(RECORD_ENTRY, &cname, &hit.key, None, false)?;
            }
            if existed {
                // The registry record itself dies silently: it is bookkeeping,
                // not data, and the memory store fires Delete events for keys
                // only.
                client.perform_remove(RECORD_REGISTRY, &cname, "", None, false)?;
            }
            Ok(existed)
        })
        .await
    }
}

#[async_trait]
impl AsyncChangeFeed for ShmStore {
    async fn subscribe(&self, request: ChangeFeedRequest) -> Result<Box<dyn crate::change::ChangeStream + Send>> {
        let (next_revision, generation) = self
            .mutate(move |client| client.subscribe_point(&request.start))
            .await?;
        Ok(Box::new(ShmChangeStream::new(
            Arc::clone(&self.client),
            next_revision,
            generation,
            request.filter,
        )))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::change::ChangeStart;

    fn temp_path(name: &str) -> PathBuf {
        let mut path = std::env::temp_dir();
        path.push(format!(
            "openkeyv-shm-store-{}-{name}",
            std::process::id()
        ));
        path
    }

    #[tokio::test]
    async fn put_get_delete_roundtrip() {
        let path = temp_path("roundtrip");
        let store = ShmStore::create(
            ShmCreateConfig::new(&path).with_capacity_bytes(16 * 1024 * 1024),
        )
        .unwrap();

        store.put("alpha", Value::utf8("one"), None, None).await.unwrap();
        let value = store.get("alpha", None).await.unwrap().unwrap();
        assert_eq!(value, Value::utf8("one"));

        let removed = store.delete("alpha", None).await.unwrap();
        assert!(removed);
        assert!(store.get("alpha", None).await.unwrap().is_none());
        let _ = std::fs::remove_file(&path);
    }

    #[tokio::test]
    async fn subscribe_requires_change_feed() {
        let path = temp_path("subscribe");
        let store = ShmStore::create(
            ShmCreateConfig::new(&path)
                .with_capacity_bytes(16 * 1024 * 1024)
                .with_change_retention(0),
        )
        .unwrap();
        assert!(!store.change_feed_enabled());
        let error = match store
            .subscribe(ChangeFeedRequest {
                start: ChangeStart::Latest,
                filter: Default::default(),
            })
            .await
        {
            Err(error) => error,
            Ok(_) => panic!("subscribing to a feed-less store must fail"),
        };
        assert!(error.to_string().contains("change_retention"));
        let _ = std::fs::remove_file(&path);
    }
}
